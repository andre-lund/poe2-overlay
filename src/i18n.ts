const DICTS: Record<Lang, Dict> = { en: EN, ru: RU, de: DE, fr: FR, es: ES, pt: PT, ja: JA, ko: KO, th: TH };

function asLang(lang: string | undefined | null): Lang {
  return lang && lang in DICTS ? (lang as Lang) : "en";
}

/// UI string `key` in `lang` (English fallback), `{name}` placeholders filled.
export function t(lang: string | undefined | null, key: string, params: Record<string, string | number> = {}): string {
  const s = DICTS[asLang(lang)][key] ?? EN[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (m, k) => (k in params ? String(params[k]) : m));
}

