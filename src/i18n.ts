/// Backend messages arrive in English; map the known ones (and the parametrized ones)
/// to the UI language. Unknown text passes through.
const MESSAGES: [RegExp, string, string[]][] = [
  [/^No matching listings$/, "msgNoMatches", []],
  [/^No priced listings$/, "msgNoPriced", []],
  [/^Invalid search \(check base type\)$/, "msgInvalid", []],
  [/^No PoE2 item under the cursor/, "msgNoItem", []],
  [/^No item$/, "msgNoItemTitle", []],
  [/^Rate limit exceeded — try again in (\d+)s$/, "msgRateExceeded", ["n"]],
  [/^Rate limit approaching — wait (\d+)s$/, "msgRateApproaching", ["n"]],
  [/^Fetch limit exceeded — wait (\d+)s$/, "msgFetchLimit", ["n"]],
  [/^Search error (\d+)$/, "msgSearchError", ["n"]],
  [/^Search failed: (.*)$/, "msgSearchFailed", ["e"]],
  [/^Fetch failed: (.*)$/, "msgFetchFailed", ["e"]],
  [/^iLvl (\d+)$/, "propIlvl", ["n"]],
  [/^Level (\d+)$/, "propLevel", ["n"]],
  [/^\+(\d+)% Quality$/, "propQuality", ["n"]],
  [/^(\d+) Sockets$/, "propSockets", ["n"]],
];

export function msg(lang: string | undefined | null, text: string | null | undefined): string {
  if (!text) return "";
  if (asLang(lang) === "en") return text;
  for (const [re, key, names] of MESSAGES) {
    const m = text.match(re);
    if (m) {
      const params: Record<string, string> = {};
      names.forEach((n, i) => (params[n] = m[i + 1]));
      return t(lang, key, params);
    }
  }
  return text;
}
